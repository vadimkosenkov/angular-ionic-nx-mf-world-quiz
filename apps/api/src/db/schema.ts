import type { QuizConfig, SubmittedAnswer } from '@world-quiz/quiz/domain';
import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  index,
  integer,
  jsonb,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

const timestampMs = (name: string) =>
  timestamp(name, { withTimezone: true, mode: 'date', precision: 3 });

/**
 * A player. Created on the first sign-in with a provider; everything the
 * player owns is deleted with this row (account deletion).
 */
export const users = pgTable('users', {
  id: uuid('id').primaryKey().defaultRandom(),
  displayName: text('display_name'),
  /** As shared by the provider; informational, never used to link accounts. */
  email: text('email'),
  /**
   * The public name on leaderboards, chosen by the player. `null` until then:
   * a default ("Player 4821") is derived from the id, so the provider's name
   * is never published without the player choosing it.
   */
  nickname: text('nickname'),
  /**
   * What this player hands to someone they want as a friend: the only way
   * to be found, because there is no directory and no search by name. It
   * is replaceable, so a code that ended up in the wrong place can be
   * retired. Filled for every row (0002/0003); the column is written by
   * the repository, which retries on the one-in-a-billion collision.
   */
  inviteCode: text('invite_code').notNull().unique(),
  createdAt: timestampMs('created_at').notNull().defaultNow(),
});

/**
 * How a user signs in: one row per provider account. The provider's stable
 * subject (`sub`) identifies the account; e-mail addresses are not used for
 * that, because they can change and Apple may hide them behind a relay.
 */
export const userIdentities = pgTable(
  'user_identities',
  {
    provider: text('provider').notNull(),
    subject: text('subject').notNull(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    email: text('email'),
    createdAt: timestampMs('created_at').notNull().defaultNow(),
  },
  (table) => [
    primaryKey({ columns: [table.provider, table.subject] }),
    index('user_identities_user_idx').on(table.userId),
  ],
);

/**
 * Refresh tokens, stored as SHA-256 hashes only: a database leak does not
 * leak usable tokens.
 *
 * Tokens rotate: each refresh marks the presented token as used and issues a
 * new one in the same family. A used or revoked token presented again means
 * it was copied, so the whole family is revoked (reuse detection).
 */
export const refreshTokens = pgTable(
  'refresh_tokens',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** All tokens descending from one sign-in. */
    familyId: uuid('family_id').notNull(),
    tokenHash: text('token_hash').notNull().unique(),
    createdAt: timestampMs('created_at').notNull(),
    expiresAt: timestampMs('expires_at').notNull(),
    /** Set when the token was exchanged for a new one. */
    usedAt: timestampMs('used_at'),
    /** Set when the family was revoked (sign-out, reuse detected). */
    revokedAt: timestampMs('revoked_at'),
  },
  (table) => [
    index('refresh_tokens_family_idx').on(table.familyId),
    index('refresh_tokens_user_idx').on(table.userId),
  ],
);

/**
 * One finished quiz session, as graded by the server.
 *
 * Every derived number (answered, correct, duration, perfect) comes from the
 * server's replay of the session, never from the client. The columns that are
 * part of the replay input (`config`, `seed`, timestamps) are stored exactly,
 * so a session can be replayed again later (for example to rebuild progress).
 */
export const quizSessions = pgTable(
  'quiz_sessions',
  {
    /** Generated by the client once per session: the idempotency key. */
    id: uuid('id').primaryKey(),
    /** Owner. Sessions are recorded for signed-in players only. */
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    category: text('category').notNull(),
    difficulty: text('difficulty').notNull(),
    mode: text('mode').notNull(),
    scope: text('scope').notNull(),
    /** The exact configuration that was replayed. */
    config: jsonb('config').$type<QuizConfig>().notNull(),
    seed: text('seed').notNull(),
    startedAt: timestampMs('started_at').notNull(),
    finishedAt: timestampMs('finished_at').notNull(),
    endReason: text('end_reason').notNull(),
    answered: integer('answered').notNull(),
    correct: integer('correct').notNull(),
    durationMs: integer('duration_ms').notNull(),
    completed: boolean('completed').notNull(),
    perfect: boolean('perfect').notNull(),
    /**
     * SHA-256 of the canonical request. A retry with the same id must carry
     * the same session; a different body under the same id is a conflict.
     */
    requestHash: text('request_hash').notNull(),
    recordedAt: timestampMs('recorded_at').notNull().defaultNow(),
  },
  (table) => [
    index('quiz_sessions_user_recorded_idx').on(table.userId, table.recordedAt),
    check(
      'quiz_sessions_correct_le_answered',
      sql`${table.correct} <= ${table.answered}`,
    ),
    check('quiz_sessions_duration_non_negative', sql`${table.durationMs} >= 0`),
  ],
);

/** The answers of a session, in the order they were given. */
export const quizAnswers = pgTable(
  'quiz_answers',
  {
    sessionId: uuid('session_id')
      .notNull()
      .references(() => quizSessions.id, { onDelete: 'cascade' }),
    sequence: integer('sequence').notNull(),
    /** The country the question was about. */
    countryCode: text('country_code').notNull(),
    /** What the player submitted: a choice or typed text. */
    answer: jsonb('answer').$type<SubmittedAnswer>().notNull(),
    correct: boolean('correct').notNull(),
    /** `choice`, `exact`, `typo` or `incorrect`, as judged by the server. */
    judgement: text('judgement').notNull(),
    answeredAt: timestampMs('answered_at').notNull(),
  },
  (table) => [primaryKey({ columns: [table.sessionId, table.sequence] })],
);

/**
 * A run that earned a place on a public board: one row per ranked session
 * (docs/domain/leaderboard.md).
 *
 * Every ordinary session in a ranked mode is judged when it is recorded, in
 * the same transaction; a run that was not flawless simply has no row here.
 * Rankings are queries over these rows: each player's best run per board,
 * numbered in the board's order.
 */
export const leaderboardRuns = pgTable(
  'leaderboard_runs',
  {
    /** The session that was played; the row is its verdict. */
    sessionId: uuid('session_id')
      .primaryKey()
      .references(() => quizSessions.id, { onDelete: 'cascade' }),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** For example `capitals-hard-europe-fixed`. */
    board: text('board').notNull(),
    /** The board's metric: milliseconds, or correct answers. */
    score: integer('score').notNull(),
    /** The run's own length; the tie-break where the score is a count. */
    timeMs: integer('time_ms').notNull(),
    /**
     * The domain's `rankingKey`: one ascending key for every board, so a
     * single `ORDER BY` and a single index rank all 56 of them, whether the
     * best score is the lowest (a time) or the highest (a count).
     */
    rankKey: integer('rank_key').notNull(),
    /** When the server accepted the run: the first tie-break. */
    recordedAt: timestampMs('recorded_at').notNull(),
    /** Whether the run beat the player's own previous best on the board. */
    personalRecord: boolean('personal_record').notNull(),
  },
  (table) => [
    // The order a board is ranked in, and the one `DISTINCT ON` needs to
    // pick each player's best run.
    index('leaderboard_runs_best_idx').on(
      table.board,
      table.userId,
      table.rankKey,
      table.timeMs,
      table.recordedAt,
      table.sessionId,
    ),
    index('leaderboard_runs_user_idx').on(table.userId),
    check('leaderboard_runs_score_non_negative', sql`${table.score} >= 0`),
    check('leaderboard_runs_time_non_negative', sql`${table.timeMs} >= 0`),
  ],
);

/**
 * Two players who agreed to see each other's results.
 *
 * One row holds the whole relationship, in the direction it was asked in:
 * `pending` while the addressee has not answered, `accepted` once they
 * have. Asking someone who has already asked you does not make a second
 * row — it accepts theirs, which is also what makes two simultaneous
 * requests safe.
 */
export const friendships = pgTable(
  'friendships',
  {
    requesterId: uuid('requester_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    addresseeId: uuid('addressee_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** `pending` or `accepted`; a refusal deletes the row. */
    status: text('status').notNull(),
    requestedAt: timestampMs('requested_at').notNull(),
    /** When the addressee accepted; `null` while the request waits. */
    respondedAt: timestampMs('responded_at'),
  },
  (table) => [
    primaryKey({ columns: [table.requesterId, table.addresseeId] }),
    // "Who is waiting for me" and "who am I waiting for" are both lists a
    // player opens, and the friends board reads the accepted rows.
    index('friendships_addressee_idx').on(table.addresseeId, table.status),
    index('friendships_requester_idx').on(table.requesterId, table.status),
    // One row per pair, whichever way round it was asked. The primary key
    // alone only stops the same request arriving twice: two people asking
    // each other at the same moment write two different keys, and both
    // inserts would be let through — leaving each of them in the other's
    // incoming *and* outgoing list. With this index the second insert
    // conflicts, and the repository looks again and accepts the first.
    uniqueIndex('friendships_pair_idx').on(
      sql`least(${table.requesterId}, ${table.addresseeId})`,
      sql`greatest(${table.requesterId}, ${table.addresseeId})`,
    ),
    check(
      'friendships_not_self',
      sql`${table.requesterId} <> ${table.addresseeId}`,
    ),
    check(
      'friendships_status',
      sql`${table.status} in ('pending', 'accepted')`,
    ),
  ],
);

export const schema = {
  users,
  userIdentities,
  friendships,
  refreshTokens,
  quizSessions,
  quizAnswers,
  leaderboardRuns,
};
export type Schema = typeof schema;
